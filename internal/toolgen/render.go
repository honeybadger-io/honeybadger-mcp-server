package toolgen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
)

// Generate builds the tools and renders them as the hbmcp package's
// zz_generated_tools.go.
func Generate(bundle, overlay []byte) ([]byte, error) {
	tools, handwritten, err := build(bundle, overlay)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by toolgen. DO NOT EDIT.\n")
	b.WriteString("// Sources: openapi/bundled.yaml and openapi/tools.yaml; run make generate.\n\n")
	b.WriteString("package hbmcp\n\nimport \"github.com/mark3labs/mcp-go/mcp\"\n\n")

	b.WriteString("// generatedTools are the tool definitions, keyed by name.\n")
	b.WriteString("var generatedTools = map[string]mcp.Tool{\n")
	for _, t := range tools {
		writeTool(&b, t)
	}
	b.WriteString("}\n\n")

	b.WriteString("// generatedStrictSchemas are the schemas calls are checked against, for the\n")
	b.WriteString("// tools whose advertised schema leaves a shallow parameter's shape out.\n")
	b.WriteString("var generatedStrictSchemas = map[string]map[string]any{\n")
	for _, t := range tools {
		if t.StrictSchema == nil {
			continue
		}
		fmt.Fprintf(&b, "%q: ", t.Name)
		writeValue(&b, t.StrictSchema)
		b.WriteString(",\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// generatedShallowTopics names, per tool and parameter, the get_reference\n")
	b.WriteString("// topic that describes a shallow parameter's shape.\n")
	b.WriteString("var generatedShallowTopics = map[string]map[string]string{\n")
	for _, t := range tools {
		if len(t.Shallow) == 0 {
			continue
		}
		fmt.Fprintf(&b, "%q: {", t.Name)
		for _, p := range sortedKeys(t.Shallow) {
			fmt.Fprintf(&b, "%q: %q, ", p, t.Shallow[p])
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// generatedHandwritten are the tools whose definitions stay in Go.\n")
	fmt.Fprintf(&b, "var generatedHandwritten = %#v\n", handwritten)

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}
	return src, nil
}

// writeTool writes one tool as an mcp.Tool literal. A delete gated on confirm
// gets the confirm parameter and note from the hbmcp package, where the gate is.
func writeTool(b *bytes.Buffer, t Tool) {
	fmt.Fprintf(b, "%q: {\nName: %q,\n", t.Name, t.Name)
	desc := strconv.Quote(t.Description)
	if t.Confirm {
		desc += " + confirmNote"
	}
	fmt.Fprintf(b, "Description: %s,\n", desc)
	b.WriteString("InputSchema: mcp.ToolInputSchema{\nType: \"object\",\nProperties: map[string]any{\n")
	props := t.Schema["properties"].(map[string]any)
	for _, name := range sortedKeys(props) {
		fmt.Fprintf(b, "%q: ", name)
		writeValue(b, props[name])
		b.WriteString(",\n")
	}
	if t.Confirm {
		b.WriteString("\"confirm\": confirmParam,\n")
	}
	b.WriteString("},\n")
	if req := asSlice(t.Schema["required"]); len(req) > 0 {
		b.WriteString("Required: []string{")
		for _, r := range req {
			fmt.Fprintf(b, "%q, ", r)
		}
		b.WriteString("},\n")
	}
	b.WriteString("AdditionalProperties: false,\n},\n")
	fmt.Fprintf(b, "Annotations: mcp.ToolAnnotation{\nTitle: %q,\nReadOnlyHint: mcp.ToBoolPtr(%t),\nDestructiveHint: mcp.ToBoolPtr(%t),\n},\n},\n",
		t.Title, t.ReadOnly, !t.ReadOnly)
}

// writeValue writes a decoded YAML/JSON value as a Go literal.
func writeValue(b *bytes.Buffer, v any) {
	switch x := v.(type) {
	case nil:
		b.WriteString("nil")
	case bool:
		fmt.Fprintf(b, "%t", x)
	case string:
		b.WriteString(strconv.Quote(x))
	case int:
		fmt.Fprintf(b, "%d", x)
	case float64:
		b.WriteString(strconv.FormatFloat(x, 'g', -1, 64))
	case []any:
		b.WriteString("[]any{")
		for _, e := range x {
			writeValue(b, e)
			b.WriteString(", ")
		}
		b.WriteString("}")
	case map[string]any:
		b.WriteString("map[string]any{")
		for _, k := range sortedKeys(x) {
			fmt.Fprintf(b, "%q: ", k)
			writeValue(b, x[k])
			b.WriteString(", ")
		}
		b.WriteString("}")
	default:
		panic(fmt.Sprintf("toolgen: no Go literal for %T", v))
	}
}
